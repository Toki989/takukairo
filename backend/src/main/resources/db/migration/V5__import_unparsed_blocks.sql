-- Import Support Data only. Consumption is serialized by the parent Session lock.
CREATE TABLE import_unparsed_block (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 import_session_id BIGINT NOT NULL REFERENCES import_session(id) ON DELETE CASCADE,
 import_source_id BIGINT NOT NULL REFERENCES import_source(id) ON DELETE CASCADE,
 start_offset INTEGER NOT NULL CHECK(start_offset >= 0),
 end_offset INTEGER NOT NULL CHECK(end_offset > start_offset),
 original_text TEXT NOT NULL,
 reason TEXT NOT NULL,
 state VARCHAR(32) NOT NULL DEFAULT 'UNPROCESSED' CHECK(state IN ('UNPROCESSED','EXCLUDED','CONSUMED')),
 source_location JSONB NOT NULL DEFAULT '{}'::jsonb,
 consumption JSONB NOT NULL DEFAULT '{}'::jsonb,
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(import_session_id,import_source_id,start_offset,end_offset)
);
CREATE INDEX unparsed_session ON import_unparsed_block(import_session_id,state);
