import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {stripTypeScriptTypes} from 'node:module';
const source=await fs.readFile(new URL('../frontend/booth-preview.ts',import.meta.url),'utf8');
const output=stripTypeScriptTypes(source,{mode:'strip'});
const destination=new URL('../services/booth-preview/worker.mjs',import.meta.url);
await fs.mkdir(new URL('../services/booth-preview/',import.meta.url),{recursive:true});
await fs.writeFile(destination,'// Generated by scripts/build-booth-worker.mjs from frontend/booth-preview.ts.\n'+output);
console.log(fileURLToPath(destination));
